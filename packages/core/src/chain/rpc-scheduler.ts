/** Quota-group scheduler. Rate windows are shared across processes via rpcGateDbPath(), default on;
 * SLRD_RPC_GATE_DB (SQLite reservations); concurrency is process-local. */
import { createHash } from "crypto";
import { SharedRpcWindow, rpcGateDbPath } from "./shared-rpc-window.ts";

export type ProviderBudget = { group: string; rps: number; concurrency: number };
export type RequestPermit = { release(): void };
type Group = { active: number; queue: symbol[]; window: SharedRpcWindow };
const groups = new Map<string, Group>();
const globalWindows = new Map<string, SharedRpcWindow>();
export const MAINNET_GENESIS = "5eykt4UsFv8P8NJdTREpY1vzqKqZKvdpKuc147dw2N9d";
export const READINESS_ADDRESS = "11111111111111111111111111111111";

export function rpcSafeEndpoint(raw: string): string {
  try { const u = new URL(raw); return `${u.protocol}//${u.host}/***`; }
  catch { return "<invalid endpoint>"; }
}
/** Full URLs are never logged; the hash discriminates credentials on one host. */
export function rpcEndpointIdentity(url: string): string {
  const canonical = new URL(url).toString();
  return createHash("sha256").update(canonical).digest("hex");
}
export function providerBudget(url: string): ProviderBudget {
  const hostname = new URL(url).hostname;
  let configured: Record<string, Partial<ProviderBudget>> = {};
  try { configured = JSON.parse(process.env.SLRD_RPC_PROVIDER_LIMITS ?? "{}"); }
  catch { throw new Error("SLRD_RPC_PROVIDER_LIMITS must be a JSON object"); }
  // Hash keys take priority; hostname keys remain accepted for R8 users.
  // Configuration generated by the CLI deliberately preserves distinct plans
  // on the same host. Only an explicitly common group shares a quota window.
  const entry = configured[rpcEndpointIdentity(url)] ?? configured[hostname] ?? {};
  const group = entry.group ?? hostname;
  if (!/^[a-zA-Z0-9._:-]{1,100}$/.test(group)) throw new Error("Invalid RPC quota group");
  const rps = entry.rps ?? 5, concurrency = entry.concurrency ?? 3;
  if (!Number.isSafeInteger(rps) || rps < 1 || rps > 10000 ||
      !Number.isSafeInteger(concurrency) || concurrency < 1 || concurrency > 100)
    throw new Error("Invalid RPC provider budget");
  return { group, rps, concurrency };
}
function windowFor(group: string): Group {
  const db = rpcGateDbPath();
  const key = `${db ?? "memory"}:${group}`;
  let found = groups.get(key);
  if (!found) {
    // Hashed group ID keeps credential-opaque names out of SQLite filenames.
    const digest = createHash("sha256").update(group).digest("hex").slice(0, 20);
    found = { active: 0, queue: [],
      window: new SharedRpcWindow(db ? `${db}.${digest}` : undefined) };
    groups.set(key, found);
  }
  return found;
}
function aggregateWindow(): SharedRpcWindow {
  const key = rpcGateDbPath() ?? "memory";
  let window = globalWindows.get(key);
  if (!window) { window = new SharedRpcWindow(key === "memory" ? undefined : `${key}.aggregate`);
    globalWindows.set(key, window); }
  return window;
}
function abortError(): Error { return Object.assign(new Error("RPC request cancelled"), { name: "AbortError" }); }
export async function waitBounded(ms: number, signal: AbortSignal | null | undefined, deadline: number): Promise<void> {
  if (signal?.aborted) throw abortError();
  if (Date.now() >= deadline) throw Object.assign(new Error("RPC_QUEUE_TIMEOUT"), { code: "RPC_QUEUE_TIMEOUT" });
  await new Promise<void>((resolve, reject) => {
    const timer = setTimeout(done, Math.min(Math.max(1, ms), deadline - Date.now()));
    function done() { signal?.removeEventListener("abort", cancelled); resolve(); }
    function cancelled() { clearTimeout(timer); signal?.removeEventListener("abort", cancelled); reject(abortError()); }
    signal?.addEventListener("abort", cancelled, { once: true });
  });
  if (signal?.aborted) throw abortError();
  if (Date.now() >= deadline) throw Object.assign(new Error("RPC_QUEUE_TIMEOUT"), { code: "RPC_QUEUE_TIMEOUT" });
}
export type RpcCapacity = { available: boolean; delayMs: number; active: number;
  concurrency: number; waiting: number; group: string };
function aggregateBudget(): number {
  const value = Number(process.env.SLRD_RPC_AGGREGATE_RPS ?? 0);
  if (!Number.isSafeInteger(value) || value < 0) throw new Error("Invalid RPC aggregate budget");
  return value;
}
function permitFor(group: Group): RequestPermit {
  group.active++;
  let released = false;
  return { release() { if (!released) { released = true; group.active--; } } };
}
export class RpcScheduler {
  capacity(url: string, requests = 1, sends = 0): RpcCapacity {
    const budget = providerBudget(url), group = windowFor(budget.group);
    const aggregate = aggregateBudget();
    const delay = Math.max(group.window.delay({ maxRequests: budget.rps,
      windowMs: 1000, maxSends: 1, sendWindowMs: 1000 }, requests, sends),
      aggregate ? aggregateWindow().delay({ maxRequests: aggregate,
        windowMs: 1000 }, requests, 0) : 0);
    return { available: group.active < budget.concurrency && !group.queue.length && !delay,
      delayMs: group.active >= budget.concurrency ? Math.max(15, delay) : delay,
      active: group.active, concurrency: budget.concurrency,
      waiting: group.queue.length, group: budget.group };
  }
  private reserve(url: string, requests: number, sends: number, ticket?: symbol): RequestPermit | null {
    const budget = providerBudget(url), group = windowFor(budget.group);
    if (requests > budget.rps || sends > 1) throw new Error("RPC batch exceeds provider budget");
    if (group.active >= budget.concurrency ||
        (group.queue.length && group.queue[0] !== ticket)) return null;
    const aggregate = aggregateBudget();
    if (aggregate && requests > aggregate) throw new Error("RPC batch exceeds aggregate budget");
    // Hints avoid spending provider tokens when aggregate admission is blocked.
    // Both reservations still recheck atomically across processes; a racing
    // aggregate reservation can conservatively consume provider budget only.
    if (aggregate && aggregateWindow().delay({ maxRequests: aggregate,
      windowMs: 1000 }, requests, 0)) return null;
    if (group.window.reserve({ maxRequests: budget.rps, windowMs: 1000,
      maxSends: 1, sendWindowMs: 1000 }, requests, sends)) return null;
    if (aggregate && aggregateWindow().reserve({ maxRequests: aggregate,
      windowMs: 1000 }, requests, 0)) return null;
    return permitFor(group);
  }
  tryAcquire(url: string, requests: number, sends: number): RequestPermit | null {
    return this.reserve(url, requests, sends);
  }
  async acquire(url: string, requests: number, sends: number,
    signal?: AbortSignal | null, deadline = Date.now() + 15_000): Promise<RequestPermit> {
    return (await this.acquireAny([url], requests, sends, signal, deadline)).permit;
  }
  async acquireAny(urls: readonly string[], requests: number, sends: number,
    signal?: AbortSignal | null, deadline = Date.now() + 15_000): Promise<{url: string; permit: RequestPermit}> {
    if (signal?.aborted) throw abortError();
    const candidates = [...new Set(urls)];
    if (!candidates.length) throw new Error("RPC endpoint pool is empty");
    const quotaGroups = [...new Set(candidates.map(url => {
      const budget = providerBudget(url);
      if (requests > budget.rps || sends > 1) throw new Error("RPC batch exceeds provider budget");
      return windowFor(budget.group);
    }))];
    if (quotaGroups.every(group => group.queue.length >= 512))
      throw Object.assign(new Error("RPC_QUEUE_FULL"), { code: "RPC_QUEUE_FULL" });
    const ticket = Symbol("rpc admission");
    const joined = quotaGroups.filter(group => group.queue.length < 512);
    joined.forEach(group => group.queue.push(ticket));
    try {
      while (true) {
        if (signal?.aborted) throw abortError();
        if (Date.now() >= deadline)
          throw Object.assign(new Error("RPC_QUEUE_TIMEOUT"), { code: "RPC_QUEUE_TIMEOUT" });
        for (const url of candidates) {
          const group = windowFor(providerBudget(url).group);
          if (!joined.includes(group)) continue;
          const permit = this.reserve(url, requests, sends, ticket);
          if (permit) return { url, permit };
        }
        await waitBounded(15, signal, deadline);
      }
    } finally {
      for (const group of joined) {
        const index = group.queue.indexOf(ticket);
        if (index >= 0) group.queue.splice(index, 1);
      }
    }
  }
}
export const sharedRpcScheduler = new RpcScheduler();
