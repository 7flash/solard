import { Connection } from "@solana/web3.js";
import { getCompatibleParsedTransaction } from "../packages/core/src/chain/parsed-transaction.ts";
import { fetchCurve } from "../packages/core/src/venues/pump/state.ts";
import { quoteSolLoader, subscribeTrades, type TradeEvent } from "../packages/core/src/market/launch-trades.ts";
import type { TokenRow } from "../packages/core/src/db/schema.ts";
const configuration = Bun.TOML.parse(await Bun.file(".config.toml").text()) as { rpc: { endpoint: string } };
const connection = new Connection(process.argv.includes("--public") ? "https://api.mainnet-beta.solana.com" : configuration.rpc.endpoint, { disableRetryOnRateLimit: true });
const signature = "4X7KJJwCovRuoeVN4xUuNfKDbgZzJz2hCdFhzxtaNedNjGd3tCyCELBDw3nNDnyfJDnS7pbLqESUXWKj2gfECVMG";
const parsed = await getCompatibleParsedTransaction(connection, signature);
if (!parsed) throw new Error("Signature unavailable");
console.log({ signature, version: parsed.version, slot: parsed.slot });
await Bun.write("packages/core/src/chain/seedcat-v1.fixture.json", JSON.stringify(parsed, null, 2));
const curve = await fetchCurve(connection, { mint: "E4R6KvcnxvoHYBe872byyCeoyExGHja8n5Vo3JNWodus" } as TokenRow);
if (!curve) throw new Error("SEEDCAT curve unavailable");
const statuses: Array<string> = [];
const quoteSol = await quoteSolLoader(connection, event => statuses.push(event))(curve.quoteAsset.mint.toBase58(), curve.quoteAsset.decimals);
if (quoteSol == null) throw new Error(`Conversion unavailable: ${statuses.join(",")}`);
console.log({ quoteMint: curve.quoteAsset.mint.toBase58(), quoteDecimals: curve.quoteAsset.decimals, quoteSol, statuses });
let callback: Parameters<Connection["onLogs"]>[1] | undefined;
connection.onLogs = (_filter, handler) => { callback = handler; return 1; };
connection.removeOnLogsListener = async () => {};
connection.getParsedTransaction = async () => { throw new Error("Parsed enrichment intentionally unavailable"); };
let deliver!: (event: TradeEvent) => void;
const received = new Promise<TradeEvent>(resolve => { deliver = resolve; });
const subscription = await subscribeTrades({ connection, tokens: ["E4R6KvcnxvoHYBe872byyCeoyExGHja8n5Vo3JNWodus"], venues: ["pump"], solUsd: 100, onTrade: deliver });
callback!({ signature, err: null, logs: parsed.meta?.logMessages ?? [] }, { slot: parsed.slot });
const trade = await Promise.race([received, Bun.sleep(15_000).then(() => { throw new Error("No usable SEEDCAT trade emitted"); })]);
if (trade.market.priceSol == null || trade.market.priceUsd == null || trade.market.marketCapUsd == null) throw new Error("Incomplete SEEDCAT converted market");
const supply = Number(trade.market.supplyRaw) / 10 ** trade.market.baseDecimals;
if (Math.abs(trade.market.marketCapUsd - supply * trade.market.priceUsd) > 0.000001) throw new Error("Supply-based capitalization mismatch");
console.log({ mint: trade.mint, quoteMint: trade.market.quoteMint, quoteDecimals: trade.market.quoteDecimals, supplyRaw: String(trade.market.supplyRaw), priceSol: trade.market.priceSol, priceUsd: trade.market.priceUsd, marketCapUsd: trade.market.marketCapUsd, usdSolReference: 100 });
await subscription.close();
if (process.argv.includes("--listen")) {
  const liveConnection = new Connection("https://api.mainnet-beta.solana.com", { disableRetryOnRateLimit: true });
  const liveTrades: Array<TradeEvent> = [];
  const live = await subscribeTrades({ connection: liveConnection, tokens: [trade.mint], venues: ["pump"], solUsd: 100, onTrade: event => { liveTrades.push(event); console.log({ freshSignature: event.signature, atMs: event.atMs, priceSol: event.market.priceSol }); } });
  await Bun.sleep(45_000);
  await live.close();
  console.log({ freshTickCount: liveTrades.length, observationMs: 45_000 });
}
